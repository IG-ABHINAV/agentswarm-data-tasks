package absdiff
import "testing"
var _ func(int64, int64) uint64 = AbsDiff
func TestSpec(t *testing.T) {
cases:=[]struct{a,b int64;want uint64}{
{0,0,0},
{1,2,1},
{2,1,1},
{5,-3,8},
{-3,5,8},
{-5,-3,2},
{-3,-5,2},
{7,7,0},
{9223372036854775807,-9223372036854775808,18446744073709551615},
{-9223372036854775808,9223372036854775807,18446744073709551615},
{9223372036854775807,-1,9223372036854775808},
{-1,9223372036854775807,9223372036854775808},
{-9223372036854775808,0,9223372036854775808},
{0,-9223372036854775808,9223372036854775808},
{-9223372036854775808,1,9223372036854775809},
{1,-9223372036854775808,9223372036854775809},
{9223372036854775807,0,9223372036854775807},
{9223372036854775807,9223372036854775807,0},
{-9223372036854775808,-9223372036854775808,0},
{9007199254740993,0,9007199254740993},
{9007199254740993,-9007199254740993,18014398509481986},
{-1,0,1},
{0,-1,1},
{1000000000000000000,-1000000000000000000,2000000000000000000},
{123456789,-987654321,1111111110},
{2147483648,-2147483648,4294967296},
{4294967297,1,4294967296},
{-4294967297,0,4294967297},
{9223372036854775807,9223372036854775806,1},
{-9223372036854775807,-9223372036854775808,1},
}
for _,c:=range cases { if got:=AbsDiff(c.a,c.b);got!=c.want {t.Errorf("|%d - %d|: got %d want %d",c.a,c.b,got,c.want)};if AbsDiff(c.b,c.a)!=c.want {t.Errorf("order %d %d",c.a,c.b)};if AbsDiff(c.a,c.b)!=c.want {t.Fatal("nondeterministic")} }
for k:=uint(0);k<63;k++ { x:=int64(1)<<k; if got:=AbsDiff(x,-x);got!=2*uint64(x) {t.Errorf("1<<%d vs negative: got %d",k,got)}; if AbsDiff(x,x)!=0 || AbsDiff(-x,0)!=uint64(x) || AbsDiff(x+1,0)!=uint64(x)+1 {t.Errorf("edge at 1<<%d",k)} }
}
