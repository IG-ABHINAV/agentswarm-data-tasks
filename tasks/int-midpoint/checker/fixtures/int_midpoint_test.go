package intmidpoint
import "testing"
var _ func(int64, int64) int64 = Midpoint
func TestSpec(t *testing.T) {
cases:=[]struct{a,b,want int64}{
{0,0,0},
{1,2,1},
{2,1,1},
{1,1,1},
{3,4,3},
{1,3,2},
{7,7,7},
{-1,0,-1},
{0,-1,-1},
{-1,-2,-2},
{-3,-3,-3},
{-5,4,-1},
{4,-5,-1},
{-2,0,-1},
{9223372036854775807,9223372036854775807,9223372036854775807},
{-9223372036854775808,-9223372036854775808,-9223372036854775808},
{9223372036854775807,-9223372036854775808,-1},
{-9223372036854775808,9223372036854775807,-1},
{9223372036854775807,9223372036854775806,9223372036854775806},
{-9223372036854775808,-9223372036854775807,-9223372036854775808},
{9223372036854775807,0,4611686018427387903},
{-9223372036854775808,0,-4611686018427387904},
{-9223372036854775808,-1,-4611686018427387905},
{1000000000000000000,-999999999999999999,0},
{9007199254740993,9007199254740994,9007199254740993},
{4294967297,1,2147483649},
{-2147483648,2147483647,-1},
{123456789,-987654321,-432098766},
{9223372036854775807,1,4611686018427387904},
{-9223372036854775807,-1,-4611686018427387904},
}
for _,c:=range cases { if got:=Midpoint(c.a,c.b);got!=c.want {t.Errorf("Midpoint(%d, %d): got %d want %d",c.a,c.b,got,c.want)};if Midpoint(c.b,c.a)!=c.want {t.Errorf("order %d %d",c.a,c.b)};if Midpoint(c.a,c.b)!=c.want {t.Fatal("nondeterministic")} }
for k:=uint(0);k<63;k++ { x:=int64(1)<<k; if got:=Midpoint(x,-x);got!=0 {t.Errorf("1<<%d vs negative: got %d",k,got)}; if Midpoint(x,x)!=x || Midpoint(-x,-x)!=-x || Midpoint(x,0)!=x>>1 || Midpoint(-x,0)!=(-x)>>1 {t.Errorf("edge at 1<<%d",k)} }
}
