package saturatingadd
import "testing"
var _ func(uint64, uint64) uint64 = SaturatingAdd
func TestSpec(t *testing.T) {
cases:=[]struct{a,b,want uint64}{
{0,0,0},
{1,2,3},
{2,1,3},
{0,18446744073709551615,18446744073709551615},
{18446744073709551615,0,18446744073709551615},
{18446744073709551615,1,18446744073709551615},
{1,18446744073709551615,18446744073709551615},
{18446744073709551615,18446744073709551615,18446744073709551615},
{18446744073709551614,1,18446744073709551615},
{1,18446744073709551614,18446744073709551615},
{18446744073709551614,2,18446744073709551615},
{2,18446744073709551614,18446744073709551615},
{9223372036854775808,9223372036854775808,18446744073709551615},
{9223372036854775808,9223372036854775807,18446744073709551615},
{9223372036854775807,9223372036854775808,18446744073709551615},
{9223372036854775809,0,9223372036854775809},
{9007199254740993,0,9007199254740993},
{4294967296,4294967296,8589934592},
{4294967295,1,4294967296},
{4294967295,4294967295,8589934590},
{123456789,987654321,1111111110},
{10,18446744073709551610,18446744073709551615},
{18446744073709551610,10,18446744073709551615},
{9223372036854775807,9223372036854775807,18446744073709551614},
{9223372036854775808,9223372036854775808,18446744073709551615},
}
for _,c:=range cases { if got:=SaturatingAdd(c.a,c.b);got!=c.want {t.Errorf("%d + %d: got %d want %d",c.a,c.b,got,c.want)};if SaturatingAdd(c.a,c.b)!=c.want {t.Fatal("nondeterministic")} }
for k:=uint(0);k<64;k++ { x:=uint64(1)<<k; if got:=SaturatingAdd(x,x);(k<63&&got!=2*x)||(k==63&&got!=^uint64(0)) {t.Errorf("1<<%d doubled: got %d",k,got)}; if SaturatingAdd(^uint64(0)-x,x)!=^uint64(0) || SaturatingAdd(^uint64(0)-x+1,x)!=^uint64(0) {t.Errorf("edge at 1<<%d",k)} }
}
